"""Evaluate the RAG pipeline on eval_qa.jsonl.

Reports two families of metrics:

1. Retrieval metrics (does the hybrid FAISS+BM25 retriever find the chunk the
   question was written from?), computed per-query and averaged. Since each
   synthetic question has exactly one relevant chunk, for a given k:
     - Recall@k    = 1 if the source chunk is among the top-k retrieved, else 0
     - Precision@k = (1/k) if hit else 0   (1 relevant item among k retrieved)
     - F1@k        = harmonic mean of Recall@k and Precision@k
     - Accuracy    = Recall@1  (top-1 exact match rate; standard "accuracy"
                      framing for retrieval-only evaluation)
     - MRR         = mean reciprocal rank of the source chunk

2. Answer-quality metric (does the full RAG answer, generated by the chosen
   Ollama model from the retrieved context, actually contain the expected
   answer?), scored as SQuAD-style token-overlap F1 between the generated
   answer and the expected_answer. This is a coarse proxy, not an LLM judge --
   reported separately from the retrieval numbers so the two are never
   conflated.

Usage:
    python eval/evaluate.py --model llama3.2:3b --k 5
"""
import argparse
import json
import os
import re
import string
import sys

sys.path.insert(0, os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
import config
from rag_utils import Embedder, HybridRetriever, OllamaClient, build_rag_messages


def normalize(text: str):
    text = text.lower()
    text = re.sub(f"[{re.escape(string.punctuation)}]", " ", text)
    return text.split()


def token_f1(pred: str, gold: str):
    pred_toks = normalize(pred)
    gold_toks = normalize(gold)
    if not pred_toks or not gold_toks:
        return 0.0
    common = {}
    for t in pred_toks:
        common[t] = common.get(t, 0) + 1
    overlap = 0
    gold_counts = {}
    for t in gold_toks:
        gold_counts[t] = gold_counts.get(t, 0) + 1
    for t, c in gold_counts.items():
        overlap += min(c, common.get(t, 0))
    if overlap == 0:
        return 0.0
    precision = overlap / len(pred_toks)
    recall = overlap / len(gold_toks)
    return 2 * precision * recall / (precision + recall)


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--model", default=config.DEFAULT_OLLAMA_MODEL,
                         help="Ollama model to use for answer generation (default: %(default)s)")
    parser.add_argument("--k", type=int, default=config.TOP_K)
    parser.add_argument("--host", default=config.OLLAMA_HOST)
    parser.add_argument("--skip-generation", action="store_true",
                         help="Only compute retrieval metrics, skip the (slower) answer-quality pass")
    parser.add_argument("--limit", type=int, default=None, help="Cap number of eval questions (debug)")
    args = parser.parse_args()

    if not os.path.exists(config.EVAL_QA_PATH):
        raise SystemExit(f"{config.EVAL_QA_PATH} not found — run eval/generate_eval_set.py first.")

    qa_pairs = []
    with open(config.EVAL_QA_PATH, "r", encoding="utf-8") as f:
        for line in f:
            qa_pairs.append(json.loads(line))
    if args.limit:
        qa_pairs = qa_pairs[:args.limit]

    print(f"Loaded {len(qa_pairs)} eval questions.")
    print("Loading FAISS + BM25 hybrid retriever + embedder ...")
    store = HybridRetriever()
    embedder = Embedder()

    llm = None
    if not args.skip_generation:
        llm = OllamaClient(host=args.host, model=args.model)

    recall_hits = []
    precision_vals = []
    reciprocal_ranks = []
    answer_f1s = []
    results = []

    for i, qa in enumerate(qa_pairs, start=1):
        query_vec = embedder.encode_query(qa["question"])
        retrieved = store.search(query_vec, qa["question"], args.k)
        retrieved_ids = [r["chunk_id"] for r in retrieved]

        hit = qa["source_chunk_id"] in retrieved_ids
        recall_hits.append(1.0 if hit else 0.0)
        precision_vals.append((1.0 / args.k) if hit else 0.0)

        if hit:
            rank = retrieved_ids.index(qa["source_chunk_id"]) + 1
            reciprocal_ranks.append(1.0 / rank)
        else:
            reciprocal_ranks.append(0.0)

        record = {
            "question": qa["question"],
            "expected_answer": qa["expected_answer"],
            "source_chunk_id": qa["source_chunk_id"],
            "retrieved_chunk_ids": retrieved_ids,
            "retrieval_hit": hit,
        }

        if llm is not None:
            messages = build_rag_messages(qa["question"], retrieved)
            try:
                generated = llm.chat(messages, stream=False, temperature=0.0)
            except Exception as e:
                generated = ""
                record["generation_error"] = str(e)
            f1 = token_f1(generated, qa["expected_answer"])
            answer_f1s.append(f1)
            record["generated_answer"] = generated
            record["answer_token_f1"] = f1

        results.append(record)

        if i % 10 == 0:
            print(f"  [{i}/{len(qa_pairs)}] running Recall@{args.k}={sum(recall_hits)/len(recall_hits):.3f}")

    os.makedirs(config.EVAL_DIR, exist_ok=True)
    with open(config.EVAL_RESULTS_PATH, "w", encoding="utf-8") as f:
        for r in results:
            f.write(json.dumps(r, ensure_ascii=False) + "\n")

    n = len(qa_pairs)
    recall_at_k = sum(recall_hits) / n
    precision_at_k = sum(precision_vals) / n
    f1_at_k = (2 * precision_at_k * recall_at_k / (precision_at_k + recall_at_k)
               if (precision_at_k + recall_at_k) > 0 else 0.0)
    mrr = sum(reciprocal_ranks) / n

    print("\n" + "=" * 60)
    print(f"RETRIEVAL METRICS  (n={n}, k={args.k}, embed_model={config.EMBED_MODEL_NAME})")
    print("=" * 60)
    print(f"  Accuracy (Recall@1)   : {sum(1 for r in results if r['retrieved_chunk_ids'][:1] == [r['source_chunk_id']]) / n:.3f}")
    print(f"  Recall@{args.k}              : {recall_at_k:.3f}")
    print(f"  Precision@{args.k}           : {precision_at_k:.3f}")
    print(f"  F1@{args.k}                  : {f1_at_k:.3f}")
    print(f"  MRR                    : {mrr:.3f}")

    if llm is not None:
        avg_answer_f1 = sum(answer_f1s) / len(answer_f1s)
        print("\n" + "-" * 60)
        print(f"ANSWER QUALITY  (generation_model={args.model}, token-overlap F1 vs expected answer)")
        print("-" * 60)
        print(f"  Mean answer token-F1  : {avg_answer_f1:.3f}")
        print("  (approximate proxy, not an LLM judge -- inspect eval_results.jsonl for detail)")

    print(f"\nPer-question detail written to {config.EVAL_RESULTS_PATH}")


if __name__ == "__main__":
    main()
